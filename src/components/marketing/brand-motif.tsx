const symbolId = (motif: BrandMotifName) => `brand-motif-${motif}`;

/**
 * 모티프 경로를 문서에 한 번만 싣는 SVG 스프라이트. 로케일 레이아웃이 body 맨 앞에 둔다.
 * 발자국·생선은 앱 아이콘(ic_paw, ic_fish)과 같은 경로다.
 */
export function BrandMotifSprite() {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      focusable="false"
      className="hidden"
    >
      {motifs.map((motif) => {
        return (
          <symbol key={motif} id={symbolId(motif)} viewBox={viewBoxes[motif]}>
            {motifShape(motif)}
          </symbol>
        );
      })}
    </svg>
  );
}

/** 장식용 브랜드 모티프(발자국·생선·생선 뼈·뼈다귀). 화면 낭독기에서 숨기고 색은 currentColor를 따른다. */
export function BrandMotif({ motif, className, ...props }: BrandMotifProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={viewBoxes[motif]}
      aria-hidden="true"
      focusable="false"
      data-slot="brand-motif"
      data-motif={motif}
      className={cn("size-6 shrink-0", className)}
      {...props}
    >
      <use href={`#${symbolId(motif)}`} />
    </svg>
  );
}
